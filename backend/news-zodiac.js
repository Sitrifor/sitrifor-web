function inRange(month, day, from, to) {
  const m = month;
  const d = day;
  const [fm, fd] = from;
  const [tm, td] = to;
  if (fm <= tm) {
    return (m > fm || (m === fm && d >= fd)) && (m < tm || (m === tm && d <= td));
  }
  // wraps year (Capricorn)
  return m > fm || (m === fm && d >= fd) || m < tm || (m === tm && d <= td);
}

export function westernZodiac(month, day) {
  for (const z of WESTERN) {
    if (inRange(month, day, z.from, z.to)) {
      const profile = WESTERN_PROFILE[z.id] || WESTERN_PROFILE.aries;
      return { ...z, ...profile };
    }
  }
  return { ...WESTERN[0], ...WESTERN_PROFILE.capricorn };
}

export function chineseZodiac(year) {
  // 1900 was Rat; cycle of 12
  const idx = ((Number(year) - 1900) % 12 + 12) % 12;
  const base = CHINESE[idx];
  const profile = CHINESE_PROFILE[base.id] || CHINESE_PROFILE.rat;
  return { ...base, year: Number(year), ...profile };
}

export function formatDateRu(month, day, year) {
  const dd = String(day).padStart(2, '0');
  const mm = String(month).padStart(2, '0');
  return `${dd}.${mm}.${year}`;
}

/** Stable numeric seed for a calendar date. */
export function dateSeed(month, day, year) {
  return (Number(year) * 512 + Number(month) * 32 + Number(day)) >>> 0;
}

function mulberry32(seed) {
  let t = seed >>> 0;
  return () => {
    t += 0x6d2b79f5;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

function seededShuffle(list, seed) {
  const arr = [...(list || [])];
  const rnd = mulberry32(seed);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/** Reduce date digits to birth number 1–9. */
export function birthNumberOf(month, day, year) {
  const raw = `${String(day).padStart(2, '0')}${String(month).padStart(2, '0')}${year}`;
  let n = [...raw].reduce((s, ch) => s + Number(ch), 0);
  while (n > 9) n = [...String(n)].reduce((s, ch) => s + Number(ch), 0);
  return BIRTH_NUMBER[n] ? { n, ...BIRTH_NUMBER[n] } : { n: 1, ...BIRTH_NUMBER[1] };
}

/** Day within western sign → decan 1–3 (~10 days each). */
export function westernDecan(month, day, western) {
  const z = western || westernZodiac(month, day);
  const [fm, fd] = z.from;
  let cursorM = fm;
  let cursorD = fd;
  let idx = 0;
  for (let step = 0; step < 40; step++) {
    if (cursorM === Number(month) && cursorD === Number(day)) break;
    idx += 1;
    cursorD += 1;
    const dim = new Date(Date.UTC(2001, cursorM, 0)).getUTCDate();
    const daysInMonth = cursorM === 2 ? 29 : dim;
    if (cursorD > daysInMonth) {
      cursorD = 1;
      cursorM = cursorM === 12 ? 1 : cursorM + 1;
    }
  }
  const decanN = Math.min(3, Math.floor(idx / 10) + 1);
  const meta = DECAN_TRAITS[decanN - 1];
  return { ...meta, dayIndex: idx, signId: z.id, signName: z.name };
}

export function dayOfMonthProfile(day) {
  const d = Math.min(31, Math.max(1, Number(day) || 1));
  return { day: d, ...(DAY_OF_MONTH[d] || DAY_OF_MONTH[1]) };
}

/** Near start/end of sign – optional cusp hint (not a second sign label). */
export function cuspNote(month, day, western) {
  const z = western || westernZodiac(month, day);
  const decan = westernDecan(month, day, z);
  if (decan.dayIndex <= 1) {
    return `Дата у самого начала знака «${z.name}»: ядро символа звучит громче, соседнее влияние ещё слабое.`;
  }
  if (decan.n === 3 && decan.dayIndex >= 25) {
    return `Дата ближе к переходу из «${z.name}» дальше по кругу: допустим менее буквальный символ знака и больше личного нюанса.`;
  }
  return '';
}

/**
 * Full birth-date profile for article composer / LLM editor.
 * Nearby dates share western sign / Chinese year, but day / decan / birth number differ.
 */
export function birthProfile(month, day, year) {
  const western = westernZodiac(month, day);
  const chinese = chineseZodiac(year);
  const dateRu = formatDateRu(month, day, year);
  const dayProfile = dayOfMonthProfile(day);
  const birthNumber = birthNumberOf(month, day, year);
  const decan = westernDecan(month, day, western);
  const cusp = cuspNote(month, day, western);
  const seed = dateSeed(month, day, year);

  const pool = [
    ...seededShuffle(dayProfile.motifs || [], seed),
    ...seededShuffle(western.lucky || [], seed + 11),
    ...seededShuffle(chinese.lucky || [], seed + 29)
  ];
  const luckyMotifs = [...new Set(pool)].slice(0, 8);

  const stylePool = [...(dayProfile.styleBias || []), ...(western.styles || [])];
  const styles = [...new Set(seededShuffle(stylePool, seed + 7))].slice(0, 4);
  const placement = seededShuffle(western.placement || ['предплечье', 'плечо', 'икра'], seed + 13).slice(
    0,
    3
  );

  const dayTraits = [...new Set([...(dayProfile.traits || []), ...(birthNumber.traits || [])])].slice(0, 5);
  const blendedTraits = [
    ...dayTraits.slice(0, 2),
    ...(western.traits || []).slice(0, 2),
    ...(chinese.traits || []).slice(0, 1)
  ];
  const uniqueTraits = [...new Set(blendedTraits)].slice(0, 5);

  return {
    dateRu,
    month,
    day,
    year,
    western,
    chinese,
    dayProfile,
    birthNumber,
    decan,
    cusp,
    dayTraits,
    uniqueTraits,
    mood: dayProfile.mood || '',
    luckyMotifs,
    styles,
    placement,
    imageQueries: [
      `тату ${western.name}`,
      `tattoo ${western.id}`,
      `тату ${dayProfile.motifs?.[0] || luckyMotifs[0] || western.name}`,
      `тату ${chinese.name} китайский гороскоп`
    ]
  };
}

